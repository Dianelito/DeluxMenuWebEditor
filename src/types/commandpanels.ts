export interface CommandPanelsConfig {
  panels: {
    [key: string]: CommandPanel;
  };
}

export interface CommandPanel {
  perm?: string;
  type: 'PAGINATED' | 'STANDARD';
  rows: number;
  title: string;
  item?: {
    [key: string]: CommandPanelItem;
  };
  commands?: string[];
  'open-with-item'?: boolean;
  'item-id'?: number;
  'item-damage'?: number;
  'item-name'?: string;
  'item-lore'?: string[];
  'empty-slot-item'?: number;
  'empty-slot-item-damage'?: number;
  'empty-slot-item-name'?: string;
}

export interface CommandPanelItem {
  id: number;
  damage?: number;
  slot: number | number[];
  name: string;
  lore?: string[];
  commands?: string[];
  permission?: string;
  'close-on-click'?: boolean;
  'update-item'?: boolean;
  enchanted?: boolean;
}

export interface DeluxeMenuConfig {
  menu_title: string;
  open_command?: string | string[];
  open_commands?: string[];
  size: number;
  open_requirement?: {
    requirements: {
      [key: string]: Requirement;
    };
  };
  items: {
    [key: string]: DeluxeMenuItem;
  };
  update_interval?: number;
}

export interface DeluxeMenuItem {
  material: string;
  slot?: number;
  slots?: number[];
  data?: number;
  amount?: number;
  priority?: number;
  display_name?: string;
  lore?: string[];
  enchantments?: string[];
  item_flags?: string[];
  hide_attributes?: boolean;
  hide_enchantments?: boolean;
  update?: boolean;
  view_requirement?: {
    requirements: {
      [key: string]: Requirement;
    };
  };
  left_click_commands?: string[];
  right_click_commands?: string[];
  shift_left_click_commands?: string[];
  shift_right_click_commands?: string[];
  middle_click_commands?: string[];
  click_commands?: string[];
  left_click_requirement?: {
    requirements: {
      [key: string]: Requirement;
    };
  };
  right_click_requirement?: {
    requirements: {
      [key: string]: Requirement;
    };
  };
}

